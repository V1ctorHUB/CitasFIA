CREATE TABLE auditoria (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tabla         text NOT NULL,
  registro_id   text NOT NULL,
  operacion     text NOT NULL CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE')),
  datos_antes   jsonb,
  datos_despues jsonb,
  actor         text,
  usuario_db    text NOT NULL DEFAULT current_user,
  ocurrido_en   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX auditoria_registro_idx ON auditoria (tabla, registro_id, ocurrido_en);

-- El DUI (aunque cifrado) no se copia a la auditoría.
CREATE FUNCTION auditar_cambios() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  antes   jsonb := CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) - 'dui_cifrado' - 'dui_hash' END;
  despues jsonb := CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN to_jsonb(NEW) - 'dui_cifrado' - 'dui_hash' END;
BEGIN
  IF TG_OP = 'UPDATE' AND antes = despues THEN
    RETURN NEW;
  END IF;

  INSERT INTO auditoria (tabla, registro_id, operacion, datos_antes, datos_despues, actor)
  VALUES (
    TG_TABLE_NAME,
    COALESCE(despues, antes) ->> (TG_ARGV[0]),
    TG_OP,
    antes,
    despues,
    NULLIF(current_setting('app.actor', true), '')
  );
  RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER auditoria_solo_insercion
  BEFORE UPDATE OR DELETE ON auditoria
  FOR EACH ROW EXECUTE FUNCTION impedir_borrado();

