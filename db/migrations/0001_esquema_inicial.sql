-- Proyectos: columnas núcleo estables + atributos JSONB validados por definición
-- ---------------------------------------------------------------------------

-- Cada atributo flexible de un proyecto se declara aquí antes de usarse.
-- Cuando un atributo se vuelve estable, una migración lo promueve a columna (ver docs/BASE_DE_DATOS.md).
CREATE TABLE proyecto_campos (
  clave          text PRIMARY KEY CHECK (clave ~ '^[a-z][a-z0-9_]{0,62}$'),
  etiqueta       text NOT NULL CHECK (length(btrim(etiqueta)) BETWEEN 1 AND 120),
  tipo           text NOT NULL CHECK (tipo IN ('texto', 'numero', 'entero', 'booleano', 'fecha', 'lista')),
  requerido      boolean NOT NULL DEFAULT false,
  opciones       jsonb,
  activo         boolean NOT NULL DEFAULT true,
  creado_en      timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT proyecto_campos_opciones_lista CHECK (
    (tipo = 'lista') = (opciones IS NOT NULL)
    AND (opciones IS NULL OR (jsonb_typeof(opciones) = 'array' AND jsonb_array_length(opciones) > 0))
  )
);

CREATE TABLE proyectos (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id >= 0),
  nombre             text NOT NULL CHECK (length(btrim(nombre)) BETWEEN 2 AND 200),
  nombre_normalizado text GENERATED ALWAYS AS (normalizar_texto(nombre)) STORED UNIQUE,
  institucion_id     integer NOT NULL REFERENCES instituciones (id) ON DELETE RESTRICT,
  activo             boolean NOT NULL DEFAULT true,
  atributos          jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(atributos) = 'object'),
  creado_en          timestamptz NOT NULL DEFAULT now(),
  actualizado_en     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX proyectos_activos_idx ON proyectos (nombre_normalizado) WHERE activo;
CREATE INDEX proyectos_atributos_idx ON proyectos USING gin (atributos jsonb_path_ops);

CREATE FUNCTION validar_atributos_proyecto() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  par   record;
  campo proyecto_campos%ROWTYPE;
  texto  text;
  valido boolean;
BEGIN
  -- Los triggers BEFORE corren antes que los CHECK: se valida la forma aquí también.
  IF jsonb_typeof(NEW.atributos) IS DISTINCT FROM 'object' THEN
    RAISE EXCEPTION 'atributos debe ser un objeto JSON' USING ERRCODE = 'check_violation';
  END IF;

  FOR par IN SELECT key, value FROM jsonb_each(NEW.atributos) LOOP
    SELECT * INTO campo FROM proyecto_campos WHERE clave = par.key;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Atributo de proyecto no definido: %', par.key USING ERRCODE = 'check_violation';
    END IF;

    texto := par.value #>> '{}';
    valido := CASE campo.tipo
      WHEN 'texto'    THEN jsonb_typeof(par.value) = 'string' AND length(texto) <= 2000
      WHEN 'numero'   THEN jsonb_typeof(par.value) = 'number'
      WHEN 'entero'   THEN jsonb_typeof(par.value) = 'number' AND texto ~ '^-?\d+$'
      WHEN 'booleano' THEN jsonb_typeof(par.value) = 'boolean'
      WHEN 'fecha'    THEN jsonb_typeof(par.value) = 'string' AND texto ~ '^\d{4}-\d{2}-\d{2}$'
                          AND to_char(to_date(texto, 'YYYY-MM-DD'), 'YYYY-MM-DD') = texto
      WHEN 'lista'    THEN jsonb_typeof(par.value) = 'string' AND campo.opciones ? texto
      ELSE false
    END;
    IF NOT valido THEN
      RAISE EXCEPTION 'Valor inválido para el atributo % (tipo %)', par.key, campo.tipo
        USING ERRCODE = 'check_violation';
    END IF;
  END LOOP;

  FOR campo IN SELECT * FROM proyecto_campos WHERE requerido AND activo LOOP
    IF NOT NEW.atributos ? campo.clave THEN
      RAISE EXCEPTION 'Falta el atributo requerido % en el proyecto', campo.clave
        USING ERRCODE = 'check_violation';
    END IF;
  END LOOP;

  RETURN NEW;
END;
$$;

-- Un campo solo puede volverse requerido cuando todos los proyectos activos ya lo tienen,
-- y no se elimina mientras algún proyecto lo use (se desactiva).
CREATE FUNCTION proteger_proyecto_campos() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF EXISTS (SELECT 1 FROM proyectos WHERE atributos ? OLD.clave) THEN
      RAISE EXCEPTION 'El atributo % está en uso; desactívalo en lugar de eliminarlo.', OLD.clave
        USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN OLD;
  END IF;

  IF TG_OP = 'UPDATE' AND NEW.tipo <> OLD.tipo
     AND EXISTS (SELECT 1 FROM proyectos WHERE atributos ? OLD.clave) THEN
    RAISE EXCEPTION 'No se puede cambiar el tipo del atributo % mientras esté en uso.', OLD.clave
      USING ERRCODE = 'restrict_violation';
  END IF;

  IF NEW.requerido AND NEW.activo
     AND EXISTS (SELECT 1 FROM proyectos WHERE activo AND NOT atributos ? NEW.clave) THEN
    RAISE EXCEPTION 'Hay proyectos activos sin el atributo %; complétalos antes de marcarlo requerido.', NEW.clave
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER proyectos_validar_atributos
  BEFORE INSERT OR UPDATE OF atributos ON proyectos
  FOR EACH ROW EXECUTE FUNCTION validar_atributos_proyecto();

CREATE TRIGGER proyecto_campos_proteger
  BEFORE INSERT OR UPDATE OR DELETE ON proyecto_campos
  FOR EACH ROW EXECUTE FUNCTION proteger_proyecto_campos();

-- ---------------------------------------------------------------------------
-- Estudiantes (identidad) y citas (hechos de cada solicitud)
-- ---------------------------------------------------------------------------

-- El DUI se guarda cifrado (AES-256-GCM) y su unicidad se garantiza con un HMAC-SHA256;
-- ambas claves viven fuera de la base (ver lib/db/dui-crypto.mjs).
CREATE TABLE estudiantes (
  id                   bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  carnet               text NOT NULL UNIQUE CHECK (carnet ~ '^[0-9]{8}$'),
  correo_institucional text GENERATED ALWAYS AS (carnet || '@uca.edu.sv') STORED,
  dui_hash             bytea NOT NULL UNIQUE CHECK (octet_length(dui_hash) = 32),
  dui_cifrado          bytea NOT NULL CHECK (octet_length(dui_cifrado) BETWEEN 30 AND 64),
  nombre_completo      text NOT NULL CHECK (
    length(nombre_completo) BETWEEN 3 AND 100
    AND nombre_completo = btrim(nombre_completo)
    AND nombre_completo !~ '\s{2,}'
    AND nombre_completo !~ '[<>{}\[\]0-9@#$%^&*=+|\\/;:"]'
  ),
  genero               genero NOT NULL,
  creado_en            timestamptz NOT NULL DEFAULT now(),
  actualizado_en       timestamptz NOT NULL DEFAULT now()
);

-- Cada cita guarda una copia del proyecto, institución y datos académicos al momento de la solicitud:
-- editar o desactivar un proyecto después nunca altera el historial ni los reportes BI.
CREATE TABLE citas (
  id                   bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  codigo               uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  estudiante_id        bigint NOT NULL REFERENCES estudiantes (id) ON DELETE RESTRICT,
  carrera_id           smallint NOT NULL REFERENCES carreras (id) ON DELETE RESTRICT,
  egreso_ciclo         smallint NOT NULL CHECK (egreso_ciclo BETWEEN 1 AND 3),
  egreso_anio          smallint NOT NULL CHECK (egreso_anio BETWEEN 2000 AND 2100),
  ciclo_egreso         text GENERATED ALWAYS AS (lpad(egreso_ciclo::text, 2, '0') || '/' || egreso_anio::text) STORED,
  proyecto_id          integer NOT NULL REFERENCES proyectos (id) ON DELETE RESTRICT,
  proyecto_nombre      text NOT NULL,
  institucion_nombre   text NOT NULL,
  origen               origen_cita NOT NULL,
  estado               estado_cita NOT NULL DEFAULT 'SOLICITADA',
  asistencia           asistencia_cita NOT NULL DEFAULT 'PENDIENTE',
  fecha_hora           timestamptz,
  fecha_hora_tentativa timestamptz,
  comentario_estudiante text CHECK (length(comentario_estudiante) <= 500),
  clave_idempotencia   uuid UNIQUE,
  cancelado_en         timestamptz,
  creado_en            timestamptz NOT NULL DEFAULT now(),
  actualizado_en       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT citas_solicitada_sin_horario CHECK (estado <> 'SOLICITADA' OR fecha_hora IS NULL),
  CONSTRAINT citas_agendada_con_horario CHECK (estado IN ('SOLICITADA', 'CANCELADA') OR fecha_hora IS NOT NULL),
  CONSTRAINT citas_asistencia_solo_confirmada CHECK (asistencia = 'PENDIENTE' OR estado = 'CONFIRMADA'),
  CONSTRAINT citas_cancelacion_consistente CHECK ((estado = 'CANCELADA') = (cancelado_en IS NOT NULL)),
  CONSTRAINT citas_formulario_idempotente CHECK (origen <> 'FORMULARIO' OR clave_idempotencia IS NOT NULL)
);

-- Un estudiante no puede tener dos solicitudes abiertas a la vez (evita duplicados por doble envío).
CREATE UNIQUE INDEX citas_una_abierta_por_estudiante
  ON citas (estudiante_id)
  WHERE estado <> 'CANCELADA' AND asistencia = 'PENDIENTE';

CREATE INDEX citas_bandeja_idx ON citas (creado_en) WHERE estado = 'SOLICITADA';
CREATE INDEX citas_calendario_idx ON citas (fecha_hora) WHERE fecha_hora IS NOT NULL;
CREATE INDEX citas_creado_en_idx ON citas (creado_en);
CREATE INDEX citas_proyecto_idx ON citas (proyecto_id);
CREATE INDEX citas_carrera_idx ON citas (carrera_id);

