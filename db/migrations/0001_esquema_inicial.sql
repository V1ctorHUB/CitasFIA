CREATE TYPE genero AS ENUM ('femenino', 'masculino', 'otro', 'prefiero-no-indicarlo');

CREATE TYPE estado_cita AS ENUM (
  'SOLICITADA',                -- en bandeja, sin horario
  'PENDIENTE_CONFIRMACION',    -- ubicada en calendario, correo enviado
  'ACEPTADA_ESTUDIANTE',       -- el estudiante aceptó en el mini portal
  'REPROGRAMACION_SOLICITADA', -- el estudiante propuso otra hora
  'CONFIRMADA',                -- sellada por coordinación
  'CANCELADA'                  -- "Eliminar Cita": se conserva para estadística
);

CREATE TYPE asistencia_cita AS ENUM ('PENDIENTE', 'ASISTIO', 'NO_ASISTIO');

CREATE TYPE origen_cita AS ENUM ('FORMULARIO', 'MANUAL');

