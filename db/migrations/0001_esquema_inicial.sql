-- Misma normalización que normalizeSearchText en el cliente: sin tildes, minúsculas, espacios simples.
CREATE FUNCTION normalizar_texto(texto text) RETURNS text
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
RETURN lower(translate(btrim(regexp_replace(texto, '\s+', ' ', 'g')), 'ÁÉÍÓÚÜÑáéíóúüñ', 'AEIOUUNaeiouun'));

CREATE FUNCTION fijar_actualizado_en() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.actualizado_en := now();
  RETURN NEW;
END;
$$;

CREATE FUNCTION impedir_borrado() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'No se permite eliminar filas de %; desactívalas o cancélalas.', TG_TABLE_NAME
    USING ERRCODE = 'restrict_violation';
END;
$$;

