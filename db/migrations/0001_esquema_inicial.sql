CREATE TABLE carreras (
  id         smallint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  nombre     text NOT NULL UNIQUE CHECK (length(nombre) BETWEEN 2 AND 120),
  facultad   text NOT NULL CHECK (length(facultad) BETWEEN 2 AND 120),
  activa     boolean NOT NULL DEFAULT true,
  creado_en  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE instituciones (
  id                 integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  nombre             text NOT NULL CHECK (length(btrim(nombre)) BETWEEN 2 AND 200),
  nombre_normalizado text GENERATED ALWAYS AS (normalizar_texto(nombre)) STORED UNIQUE,
  creado_en          timestamptz NOT NULL DEFAULT now(),
  actualizado_en     timestamptz NOT NULL DEFAULT now()
);

